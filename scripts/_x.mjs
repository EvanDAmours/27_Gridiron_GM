import fs from "node:fs";
import { preview } from "vite";
import { chromium } from "playwright-core";
const save = fs.readFileSync("/tmp/claude-0/wk5_save.txt", "utf8");
const server = await preview({ build: { outDir: "node_modules/.dist2" }, preview: { port: 4308, strictPort: false }, logLevel: "silent" });
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const out = process.argv[2];
const page = await b.newPage({ viewport: { width: 1300, height: 820 } });
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
await page.addInitScript((s) => { if (!sessionStorage.getItem("x")) { localStorage.setItem("gm_autosave", s); localStorage.setItem("gm_theme", "light"); localStorage.setItem("gm_intro_shown", "1"); sessionStorage.setItem("x", "1"); sessionStorage.setItem("gm_preview", "1"); } }, save);
await page.goto(server.resolvedUrls.local[0]);
await page.getByText(/CONTINUE/).first().click();
await page.waitForTimeout(2500);
await page.mouse.click(5, 815); await page.waitForTimeout(300);
const nav = async (t) => { await page.locator("nav.hdr-tabs button", { hasText: t }).first().click({ force: true }); await page.waitForTimeout(1000); };
await page.screenshot({ path: `${out}/l-home.png` });
await nav("Stats"); await page.getByRole("button", { name: /Award races/ }).click(); await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/l-races.png` });
await nav("League"); await page.getByRole("button", { name: "Transactions" }).first().click(); await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/l-wire.png` });
await page.locator("button", { hasText: "☰" }).first().click(); await page.waitForTimeout(400); await page.getByText("Saves & Cap 101").first().click(); await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/l-saves.png` });
console.log("errors", errs.slice(0, 3));
await b.close(); server.httpServer.close();
