"""Fetches current Madden ratings from EA's ratings site and writes
nfl-rosters.js (the player data used by nfl-mod.js).

    python3 tools/nfl/fetch_rosters.py

Only the facts needed by the game are kept: name, position, overall, age,
speed and development trait.
"""
import json, os, re, time, urllib.request, urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "public", "retro", "nfl-rosters.js")
# EA's ratings site (current Madden edition and ratings week). The page's Next.js data
# route returns players with team and position, filtered by team.
PAGE = "https://www.ea.com/games/madden-nfl/ratings"
DATA = "https://www.ea.com/_next/data/{build}/en/games/madden-nfl/ratings.json"
POSITIONS = {"QB", "HB", "FB", "WR", "TE", "LT", "LG", "C", "RG", "RT", "DT", "LEDG", "REDG",
             "MIKE", "WILL", "SAM", "CB", "FS", "SS", "K", "P"}
# Retro Bowl uid (Teams.txt order) -> EA team id
EA_TEAM = [3, 12, 22, 18, 4, 9, 8, 23, 25, 2, 5, 29, 32, 10, 17, 30,
           11, 16, 13, 26, 7, 24, 15, 28, 1, 19, 20, 31, 14, 21, 27, 6]
UA = {"User-Agent": "Mozilla/5.0 (RetroBowlRoster roster script)"}


def fetch(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40) as r:
                return r.read().decode("utf-8")
        except Exception:
            time.sleep(2 ** attempt)
    raise RuntimeError("request failed: " + url)


def build_id():
    m = re.search(r'"buildId":"([^"]+)"', fetch(PAGE))
    if not m:
        raise RuntimeError("could not find the ratings site build id")
    return m.group(1)


def team_players(build, ea_team):
    out, page = [], 1
    while True:
        q = urllib.parse.urlencode({"franchiseSlug": "madden-nfl", "team": ea_team, "page": page})
        details = json.loads(fetch(DATA.format(build=build) + "?" + q))["pageProps"]["ratingDetails"]
        out += details["items"]
        if not details["items"] or len(out) >= details.get("totalItems", 0):
            return out
        page += 1


def dev(p):
    kinds = {(a.get("type") or {}).get("id") for a in p.get("playerAbilities") or []}
    return "X" if "xFactor" in kinds else "S" if "superstarAbility" in kinds else "N"


def main():
    build = build_id()
    teams, label = [], ""
    for uid, ea in enumerate(EA_TEAM):
        players = []
        for p in team_players(build, ea):
            pos = (p.get("position") or {}).get("id")
            if pos not in POSITIONS:
                continue
            stats = p.get("stats") or {}
            label = (p.get("iteration") or {}).get("label", label)
            players.append(dict(
                fn=p["firstName"], ln=p["lastName"], pos=pos,
                ovr=int(p["overallRating"]), age=int(p.get("age") or 25),
                spd=int((stats.get("speed") or {}).get("value", 70)), dev=dev(p)))
        # best first; ties go to the younger player
        players.sort(key=lambda x: (-x["ovr"], x["age"]))
        teams.append(players)
        print(uid, ea, len(players), players[0]["fn"] + " " + players[0]["ln"] if players else "-")
    edition = re.search(r"madden-nfl-(\d+)", json.dumps(teams) + fetch(PAGE))
    with open(OUT, "w") as f:
        f.write("// Generated by tools/nfl/fetch_rosters.py from Madden NFL %s ratings (%s).\n"
                % (edition.group(1) if edition else "", label))
        f.write("// Index == team uid in html5game/Teams.txt. Do not edit by hand.\n")
        f.write("window.NFL_ROSTERS = " + json.dumps(teams, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
